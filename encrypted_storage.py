from abc import ABC, abstractmethod
from Cryptodome.Cipher import ChaCha20_Poly1305
from Cryptodome.Protocol.KDF import scrypt
import secrets
import logging


class EncryptedStorage(ABC):
    """A class for securely storing and retrieving encrypted data in Storage.

    It utilizes the XChaCha20-Poly1305 authenticated encryption algorithm and
    derives cryptographic keys from plain passwords using the scrypt KDF.
    The resulting encrypted payload is stored remotely on Storage.
    """

    def __init__(self, password: str | bytes,
                 salt_len: int = 32):

        """Initializes the EncryptedStorage instance with credentials and configuration.

        Args:
            password: A plain text password string or a pre-derived byte key.
            salt_len: The length of the salt in bytes used for scrypt KDF.

        Raises:
            ValueError: If any of the arguments do not match their expected types.
        """

        self.salt_len = salt_len

        self.nonce_len = 24
        self.tag_len = 16
        self.key_len = 32

        if isinstance(password, str):
            self.key_str = password
            self.key = None
        elif isinstance(password, bytes):
            if len(password) != self.key_len:
                raise ValueError("Password length must be equal to self.key_len")
            logging.info("Using bytes as key")
            self.key = password
        else:
            raise ValueError("password must be str or bytes")

    def get_key(self, salt: bytes | None = None) -> bytes:
        """Retrieves or derives the byte encryption key.

        If a string password was provided during initialization, this method
        uses scrypt to derive a secure cryptographic key using the provided salt.

        Args:
            salt: The salt bytes. Required if a string password is being used.
            n: Scrypt N.

        Returns:
            A byte cryptographic key as bytes.

        Raises:
            ValueError: If salt is missing or its length does not equal self.salt_len.
        """
        if not self.key:
            if salt is None: raise ValueError("Salt must be provided")
            if len(salt) != self.salt_len:
                raise ValueError("Salt length must be equal to self.salt_len")
            return scrypt(self.key_str, salt, self.key_len, 2**17, 8, 1)  # type: ignore
        else:
            return self.key

    def encrypt(self, data: bytes) -> tuple[bytes, bytes, bytes, bytes]:
        """Encrypts binary data using the XChaCha20-Poly1305 algorithm.

        Generates a unique random salt and nonce for each encryption operation.

        Args:
            data: The raw binary data to encrypt.

        Returns:
            A tuple containing:
                - enc (bytes): The encrypted ciphertext.
                - tag (bytes): The byte authentication tag for integrity verification.
                - nonce (bytes): The byte initialization vector.
                - salt (bytes): The salt used during key derivation.
        """
        logging.info("Encrypting...")
        nonce = secrets.token_bytes(self.nonce_len)
        salt = secrets.token_bytes(self.salt_len)
        cipher = ChaCha20_Poly1305.new(key=self.get_key(salt), nonce=nonce)
        enc, tag = cipher.encrypt_and_digest(data)
        logging.info("Encrypted")
        return enc, tag, nonce, salt

    def decrypt(self, enc: bytes, tag: bytes, nonce: bytes, salt: bytes) -> bytes | None:
        """Decrypts the ciphertext and verifies its authenticity.

        Args:
            enc: The encrypted ciphertext bytes.
            tag: The byte authentication tag.
            nonce: The byte initialization vector.
            salt: The salt used for key derivation.

        Returns:
            The decrypted raw bytes, or None if the ciphertext is empty.

        Raises:
            ValueError: If arguments are not bytes or if decryption/verification fails.
        """
        if not enc:
            return None
        logging.info("Decrypting...")
        cipher = ChaCha20_Poly1305.new(key=self.get_key(salt), nonce=nonce)
        try:
            dec = cipher.decrypt_and_verify(enc, tag)
        except ValueError:
            raise ValueError("Decryption failed")
        return dec

    @abstractmethod
    def send(self, data: bytes) -> bool:
        """Abstract send

        Args:
            data: The binary data to send.

        Returns:
            Bool successful state
        """
        pass

    @abstractmethod
    def get(self) -> bytes | None:
        """Abstract get

        Returns:
            The binary content, or None if the file is empty or decoding fails.

        Raises:
            ValueError: If fail to get
        """
        pass

    def encrypt_and_send(self, data: str) -> bool:
        """Encrypts a string and uploads the bundled payload to the Storage.

        Packets the salt, nonce, tag, and ciphertext together into a single
        contiguous byte array before transmission.

        Args:
            data: The plain text string to encrypt and upload.

        Returns:
            True if the payload was successfully sent to the Storage, False otherwise.
        """
        data_bytes = data.encode('utf-8')
        enc, tag, nonce, salt = self.encrypt(data_bytes)
        content = salt + nonce + tag + enc
        successful = self.send(content)
        return successful

    def get_and_decrypt(self) -> str:
        """Fetches the bundled payload from Storage, decrypts it, and returns the text.

        Automatically extracts the individual cryptographic components (salt, nonce,
        tag, and ciphertext) from the retrieved byte array to perform decryption.

        Returns:
            The decrypted and verified plain text string (UTF-8).

        Raises:
            ValueError: If the remote payload is malformed, too short, decryption
                fails, or the resulting bytes cannot be decoded to UTF-8.
        """
        content = self.get()
        if content:
            if len(content) < self.salt_len + self.nonce_len + self.tag_len: raise ValueError("Too short")
            salt, nonce, tag, enc = (content[:self.salt_len], content[self.salt_len:self.salt_len + self.nonce_len],
                                     content[
                                         self.salt_len + self.nonce_len:self.salt_len + self.nonce_len + self.tag_len],
                                     content[self.salt_len + self.nonce_len + self.tag_len:])

            dec = self.decrypt(enc, tag, nonce, salt)
            if dec:
                try:
                    dec_str = dec.decode('utf-8')
                    return dec_str
                except UnicodeDecodeError:
                    raise ValueError("Decode to string failed")
            else:
                raise ValueError("Decryption failed")
        else:
            raise ValueError("No data to decrypt")
